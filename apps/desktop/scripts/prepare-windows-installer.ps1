$ErrorActionPreference = 'Stop'

$desktop = Split-Path -Parent $PSScriptRoot
$native = Join-Path $desktop 'native'
$output = Join-Path $desktop 'build\installer-generated'
$config = Join-Path $output 'installer-config.nsh'

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
$visualStudio = & $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $visualStudio) {
    throw 'Building the Windows NSIS installer requires Visual Studio C++ Build Tools.'
}
$vcvars = Join-Path $visualStudio 'VC\Auxiliary\Build\vcvars32.bat'
New-Item -ItemType Directory -Force -Path $output | Out-Null

$statusSource = Join-Path $native 'installer-update-status'
$source = Join-Path $statusSource 'update-status.cpp'
$status = Join-Path $output 'OneKeyUpdateStatus'
$compiler = Join-Path $output 'compile-update-status.cmd'
$compile = 'cl.exe /nologo /LD /std:c++17 /O2 /MT /W4 /WX /utf-8 /DUNICODE /D_UNICODE /Fo"{0}.obj" "{1}" "{0}.res" /link /OUT:"{0}.dll" /IMPLIB:"{0}.lib" user32.lib gdi32.lib shell32.lib' -f $status, $source
[IO.File]::WriteAllLines($compiler, @(
    '@echo off'
    ('call "{0}"' -f $vcvars)
    'if errorlevel 1 exit /b %errorlevel%'
    ('cd /d "{0}"' -f $statusSource)
    'if errorlevel 1 exit /b %errorlevel%'
    ('rc.exe /nologo /fo "{0}.res" update-status.rc' -f $status)
    'if errorlevel 1 exit /b %errorlevel%'
    $compile
), [Text.Encoding]::Default)
Push-Location -LiteralPath $output
try {
    & $env:ComSpec /d /c '.\compile-update-status.cmd'
    if ($LASTEXITCODE -ne 0) {
        throw 'Compiling the Windows installer update status failed.'
    }
} finally {
    Pop-Location
}

$configLines = @(
    '; Generated by prepare-windows-installer.ps1.'
    '!define ONEKEY_USE_UPDATE_STATUS'
    '!define ONEKEY_USE_WIN32_INSTALLER_UI'
)
if ($env:WIN_HSM_SIGNING_ENABLED -eq 'true') {
    & (Join-Path $native 'installer-directory-recovery\build.ps1') -OutputDirectory $output
}

$cmake = Get-Command cmake.exe -ErrorAction SilentlyContinue
$cmakePath = if ($cmake) { $cmake.Source } else {
    Join-Path $visualStudio 'Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe'
}
$uiSource = Join-Path $native 'installer-native-ui'
$uiOutput = Join-Path $output 'native-ui'
& $cmakePath -S $uiSource -B $uiOutput -G 'Visual Studio 17 2022' -A Win32
if ($LASTEXITCODE -ne 0) {
    throw 'Configuring the Win32 installer renderer failed.'
}
& $cmakePath --build $uiOutput --config Release --target onekey-installer-ui
if ($LASTEXITCODE -ne 0) {
    throw 'Compiling the Win32 installer renderer failed.'
}
[IO.File]::WriteAllLines($config, $configLines, [Text.Encoding]::ASCII)
