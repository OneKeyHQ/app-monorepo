param(
    [Parameter(Mandatory = $true)][string]$MakeNsis,
    [Parameter(Mandatory = $true)][string]$AppBuilderLib,
    [Parameter(Mandatory = $true)][string]$NsisResources,
    [Parameter(Mandatory = $true)][string]$StatusPluginDir
)

$ErrorActionPreference = 'Stop'
$MakeNsis = (Resolve-Path -LiteralPath $MakeNsis).Path
$AppBuilderLib = (Resolve-Path -LiteralPath $AppBuilderLib).Path
$NsisResources = (Resolve-Path -LiteralPath $NsisResources).Path
$StatusPluginDir = (Resolve-Path -LiteralPath $StatusPluginDir).Path

$fixtureDir = Join-Path ([IO.Path]::GetTempPath()) ('onekey-status-' + [guid]::NewGuid())
New-Item -ItemType Directory -Path $fixtureDir | Out-Null
$fixtureExe = Join-Path $fixtureDir 'fixture.exe'
$flagsFile = Join-Path $fixtureDir 'fixture-flags.nsh'
$traceFile = Join-Path $fixtureDir 'plugins-path.txt'

# Use the command-line conditions generated by the installed electron-builder.
$generator = Join-Path $AppBuilderLib 'out\targets\nsis\nsisScriptGenerator.js'
$stdUtils = Join-Path $AppBuilderLib 'templates\nsis\include\StdUtils.nsh'
$nsisPlugins = Join-Path $NsisResources 'plugins\x86-unicode'
$generatedFlags = & node -e "const { NsisScriptGenerator } = require(process.argv[1]); const script = new NsisScriptGenerator(); script.addPluginDir('x86-unicode', process.argv[2]); script.include(process.argv[3]); script.flags(['updated', 'force-run']); process.stdout.write(script.build());" $generator $nsisPlugins $stdUtils
if ($LASTEXITCODE -ne 0) {
    throw 'Generating fixture flag conditions failed.'
}
[IO.File]::WriteAllLines($flagsFile, $generatedFlags)

$fixtureScript = Join-Path $PSScriptRoot 'fixture.nsi'
& $MakeNsis '/WX' '/V2' "/DFIXTURE_OUTPUT=$fixtureExe" "/DFIXTURE_FLAGS=$flagsFile" "/DONEKEY_UPDATE_STATUS_PLUGIN_DIR=$StatusPluginDir" $fixtureScript
if ($LASTEXITCODE -ne 0) {
    throw 'Building the NSIS fixture failed.'
}

Add-Type @'
using System;
using System.Runtime.InteropServices;
using System.Text;

public static class StatusWindowFixture {
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern IntPtr FindWindow(string windowClass, string windowName);

    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    private static extern IntPtr FindWindowEx(IntPtr parent, IntPtr after, string windowClass, string windowName);

    public static IntPtr FindStatusLabel(IntPtr parent) {
        return FindWindowEx(parent, IntPtr.Zero, "Static", null);
    }

    [DllImport("user32.dll")]
    public static extern bool IsWindowVisible(IntPtr window);

    [DllImport("user32.dll")]
    public static extern IntPtr GetForegroundWindow();

    [DllImport("user32.dll")]
    public static extern uint GetWindowThreadProcessId(IntPtr window, out int process);

    [DllImport("user32.dll", EntryPoint = "GetWindowLongW")]
    public static extern uint GetWindowLong(IntPtr window, int index);

    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern IntPtr SendMessageTimeout(IntPtr window, uint message, UIntPtr length,
        StringBuilder text, uint flags, uint timeout, out UIntPtr result);
}
'@

function Get-StatusWindow {
    [StatusWindowFixture]::FindWindow('OneKeyInstallerUpdateStatus', 'OneKey')
}

function Confirm-StatusCase([string]$Name, [string[]]$Arguments, [string]$ExpectedText, [int]$ExitCode, [switch]$KillOwner) {
    if ((Get-StatusWindow) -ne [IntPtr]::Zero) {
        throw 'Close the previous status fixture before running this test.'
    }
    if (Test-Path -LiteralPath $traceFile) {
        Remove-Item -LiteralPath $traceFile
    }

    $processInfo = [Diagnostics.ProcessStartInfo]::new($fixtureExe)
    $processInfo.Arguments = $Arguments -join ' '
    $processInfo.UseShellExecute = $false
    $owner = [Diagnostics.Process]::Start($processInfo)
    $statusProcess = $null
    try {
        $timer = [Diagnostics.Stopwatch]::StartNew()
        $window = [IntPtr]::Zero
        while ($timer.ElapsedMilliseconds -lt 5000 -and -not $owner.HasExited) {
            $window = Get-StatusWindow
            if ($window -ne [IntPtr]::Zero -and [StatusWindowFixture]::IsWindowVisible($window)) {
                break
            }
            Start-Sleep -Milliseconds 50
        }

        if ($ExpectedText) {
            if ($window -eq [IntPtr]::Zero -or $owner.HasExited) {
                throw "$Name did not display its status window while installing."
            }
            $statusPid = 0
            [void][StatusWindowFixture]::GetWindowThreadProcessId($window, [ref]$statusPid)
            $statusProcess = [Diagnostics.Process]::GetProcessById($statusPid)
            if ($statusPid -eq $owner.Id -or $window -eq [StatusWindowFixture]::GetForegroundWindow() -or
                ([StatusWindowFixture]::GetWindowLong($window, -20) -band 0x08000000) -eq 0) {
                throw "$Name did not present a separate, non-activating status window."
            }
            $label = [StatusWindowFixture]::FindStatusLabel($window)
            $buffer = [Text.StringBuilder]::new(256)
            $messageResult = [UIntPtr]::Zero
            $response = [StatusWindowFixture]::SendMessageTimeout(
                $label, 0x000D, [UIntPtr]::new(256), $buffer, 2, 1000, [ref]$messageResult)
            if ($response -eq [IntPtr]::Zero -or $buffer.ToString() -ne $ExpectedText) {
                throw "$Name displayed unexpected text '$buffer'."
            }
        } elseif ($window -ne [IntPtr]::Zero) {
            throw "$Name unexpectedly showed a status window."
        }

        if ($KillOwner) {
            $owner.Kill()
        }
        if (-not $owner.WaitForExit(6000) -or (-not $KillOwner -and $owner.ExitCode -ne $ExitCode)) {
            throw "$Name did not reach its intended installer exit."
        }
        if ($statusProcess -and -not $statusProcess.WaitForExit(3000)) {
            throw "$Name left its host process running."
        }
        if ((Get-StatusWindow) -ne [IntPtr]::Zero) {
            throw "$Name left its status window open."
        }
        if (-not $KillOwner -and (Test-Path -LiteralPath $traceFile)) {
            $pluginsPath = [IO.File]::ReadAllText($traceFile)
            if ($pluginsPath -and (Test-Path -LiteralPath $pluginsPath)) {
                throw "$Name left its temporary plug-in directory."
            }
        }
        Write-Output "$Name passed"
    } finally {
        if (-not $owner.HasExited) {
            $owner.Kill()
            $owner.WaitForExit()
        }
        $owner.Dispose()
        if ($statusProcess) {
            $statusProcess.Dispose()
        }
    }
}

$english = 'Updating OneKey' + [char]0x2026
$chinese = (-join (0x6B63, 0x5728, 0x66F4, 0x65B0 | ForEach-Object { [char]$_ })) + " OneKey$([char]0x2026)"

Confirm-StatusCase 'Restart update' @('/S', '--updated', '--force-run', '/locale=en-US') $english 0
Confirm-StatusCase 'Failed update' @('/S', '--updated', '--force-run', '/locale=zh-CN', '/fail') $chinese 2
Confirm-StatusCase 'Terminated installer' @('/S', '--updated', '--force-run', '/locale=en-US', '/hold') $english 0 -KillOwner
Confirm-StatusCase 'Windows blocks the status host' @('/S', '--updated', '--force-run', '/blockhost') '' 0
Confirm-StatusCase 'Quit-and-install' @('/S', '--updated') '' 0
Confirm-StatusCase 'Silent install with force-run only' @('/S', '--force-run') '' 0
Confirm-StatusCase 'Plain silent install' @('/S') '' 0
Confirm-StatusCase 'Interactive install with updater flags' @('--updated', '--force-run') '' 0
Write-Output "Fixture output is in $fixtureDir"
