param(
    [Parameter(Mandatory = $true)][string]$ThemeDirectory,
    [Parameter(Mandatory = $true)][string]$OutputFile
)
$ErrorActionPreference = 'Stop'

function Read-ThemeJson($RelativePath) {
    Get-Content -LiteralPath (Join-Path $ThemeDirectory $RelativePath) -Encoding UTF8 -Raw |
        ConvertFrom-Json
}

function Quote-Text([string]$Value) {
    'L"' + $Value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t') + '"'
}

function Write-Entry($Key, $Value) {
    $null = $output.AppendLine('    { ' + (Quote-Text $Key) + ', ' + (Quote-Text $Value) + ' },')
}

$manifest = Read-ThemeJson 'theme.json'
if ($manifest.schemaVersion -ne 1 -or $manifest.id -cne 'onekey-modern') {
    throw 'Expected the OneKey Modern theme schema version 1'
}
$tokens = Read-ThemeJson $manifest.tokens
$english = Read-ThemeJson $manifest.locales.'en-US'
$replacements = @{
    'font.family' = $tokens.typography.fontFamily
    'font.titleSize' = $tokens.typography.titleSize
    'font.bodySize' = $tokens.typography.bodySize
    'window.width' = $manifest.window.width
    'window.height' = $manifest.window.height
    'window.radius' = $manifest.window.radius
}
foreach ($entry in $tokens.colors.PSObject.Properties) {
    $replacements['color.' + $entry.Name] = $entry.Value
}

$nodeTypes = @{
    Container = 'overlay'; VerticalLayout = 'vertical'; GlassPanel = 'glass'
    HorizontalLayout = 'horizontal'; Label = 'label'; Button = 'button'
    CaptionButton = 'caption'; LightBackdrop = 'backdrop'; BrandMark = 'brand'
    AnimatedProgress = 'progress'; LegalNotice = 'legal'; SuccessMark = 'success'
    Control = 'space'
}
$attributes = @('accentcolor', 'align', 'bkcolor', 'bluecolor', 'bordercolor',
    'borderround', 'bordersize', 'brandcolor', 'canvascolor', 'childvalign', 'endcolor',
    'float', 'font', 'greencolor', 'height', 'hotbkcolor', 'hotbordercolor', 'hoticoncolor',
    'hotlinkcolor', 'hottextcolor', 'iconcolor', 'inkcolor', 'inset', 'kind', 'name', 'padding',
    'pushedbkcolor', 'pushedbordercolor', 'startcolor', 'text', 'textcolor', 'trackcolor',
    'visible', 'width', 'wordbreak', 'value')
$dynamicKeys = @('runtime.version', 'runtime.progress', 'runtime.installDirectory',
    'runtime.perUserInstallDirectory', 'runtime.perMachineInstallDirectory', 'font.emphasisBold')
$substitution = [regex]'\{\{([^{}]+)\}\}'

function Compile-Value([string]$Value) {
    $substitution.Replace($Value, {
        param($Match)
        $key = $Match.Groups[1].Value
        if ($replacements.ContainsKey($key)) { return [string]$replacements[$key] }
        if ($dynamicKeys -ccontains $key) { return $Match.Value }
        if ($key.StartsWith('string.') -and $english.PSObject.Properties[$key.Substring(7)]) {
            return $Match.Value
        }
        throw "Unknown theme template value $key"
    })
}

function Compile-Node($Element) {
    $tag = $Element.LocalName
    if (!$nodeTypes.ContainsKey($tag)) { throw "Unsupported page element $tag" }
    $items = foreach ($attribute in $Element.Attributes) {
        if ($attributes -cnotcontains $attribute.Name) { throw "Unsupported attribute $($attribute.Name)" }
        '{ ' + (Quote-Text $attribute.Name) + ', ' + (Quote-Text (Compile-Value $attribute.Value)) + ' }'
    }
    $null = $output.AppendLine(('    {{ Kind::{0}, {{ {1} }}, {{' -f $nodeTypes[$tag], ($items -join ', ')))
    foreach ($child in $Element.SelectNodes('./*')) { Compile-Node $child }
    $null = $output.AppendLine('    } },')
}

$output = [Text.StringBuilder]::new()
$null = $output.AppendLine('// Generated by compile-theme.ps1 from the OneKey Modern theme.')
$null = $output.AppendLine('const Geometry geometry{ ' + $manifest.window.width + ', ' +
    $manifest.window.height + ', ' + $manifest.window.radius + ' };')
$null = $output.AppendLine('const Dictionary colors{')
foreach ($entry in $tokens.colors.PSObject.Properties) { Write-Entry $entry.Name $entry.Value }
$null = $output.AppendLine('};')
$null = $output.AppendLine('const auto locales = [] {')
$null = $output.AppendLine('  std::map<std::wstring_view, Dictionary> result;')
foreach ($locale in $manifest.locales.PSObject.Properties) {
    $localized = Read-ThemeJson $locale.Value
    $null = $output.AppendLine('  result.emplace(' + (Quote-Text $locale.Name) + ', Dictionary{')
    foreach ($entry in $localized.PSObject.Properties) { Write-Entry $entry.Name $entry.Value }
    $null = $output.AppendLine('  });')
}
$null = $output.AppendLine('  return result;')
$null = $output.AppendLine('}();')
$null = $output.AppendLine('const auto pages = [] {')
$null = $output.AppendLine('  std::map<std::wstring_view, Page> result;')
foreach ($page in $manifest.pages.PSObject.Properties) {
    [xml]$document = Get-Content -LiteralPath (Join-Path $ThemeDirectory $page.Value) -Encoding UTF8 -Raw
    $window = $document.DocumentElement
    $fonts = $window.SelectNodes('./Font')
    $layout = $window.SelectNodes('./*[not(self::Font)]')
    if ($window.LocalName -cne 'Window' -or $layout.Count -ne 1) {
        throw "Expected one layout root in $($page.Value)"
    }
    $captionHeight = ($window.GetAttribute('caption') -split ',')[3]
    $null = $output.AppendLine('  result.emplace(' + (Quote-Text $page.Name) + ', Page{ ' + $captionHeight + ', {')
    foreach ($font in $fonts) {
        $family = Quote-Text (Compile-Value $font.GetAttribute('name'))
        $size = Compile-Value $font.GetAttribute('size')
        $bold = $font.GetAttribute('bold') -ceq '{{font.emphasisBold}}'
        $null = $output.AppendLine('    { ' + $family + ', ' + $size + ', ' + "$bold".ToLowerInvariant() + ' },')
    }
    $null = $output.AppendLine('  }, {')
    Compile-Node $layout[0]
    $null = $output.AppendLine('  } });')
}
$null = $output.AppendLine('  return result;')
$null = $output.AppendLine('}();')
[IO.File]::WriteAllText($OutputFile, $output.ToString(), [Text.UTF8Encoding]::new($false))
