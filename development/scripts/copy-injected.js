#!/usr/bin/env node

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

console.log('Copying injected files...');

function copyRecursiveSync(src, dest) {
  const exists = fs.existsSync(src);
  const stats = exists && fs.statSync(src);
  const isDirectory = exists && stats.isDirectory();
  if (isDirectory) {
    fs.mkdirSync(dest, { recursive: true });
    fs.readdirSync(src).forEach((childItemName) => {
      copyRecursiveSync(
        path.join(src, childItemName),
        path.join(dest, childItemName),
      );
    });
  } else {
    fs.copyFileSync(src, dest);
  }
}

// Function to copy file
function copyFile(src, dest) {
  fs.copyFileSync(src, dest);
  console.log(`Copied ${src} to ${dest}`);
}

// Function to create directory if it doesn't exist
function ensureDirectoryExistence(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
    console.log(`Created directory: ${dirPath}`);
  }
}

// Read injectedDesktop.js once for both generated outputs
const injectedDesktopSrc =
  './node_modules/@onekeyfe/cross-inpage-provider-injected/dist/injected/injectedDesktop.js';
const injectedCode = fs.readFileSync(injectedDesktopSrc, 'utf-8');

// Generate injectedDesktopCode.text-js: text module imported by DesktopApiWebview.ts
// Contains the require shim + injectedDesktop.js, ready to executeJavaScript in page world.
(function generateInjectedTextModule() {
  const requireShim = [
    'var require=function(m){',
    'if(m==="electron"){return{ipcRenderer:{',
    'on:function(ch,cb){window.__onekeyDesktopBridge.onHostMessage(function(d){cb({},d);});},',
    'sendToHost:function(ch,d){window.__onekeyDesktopBridge.sendToHost(ch,d);}',
    '}};}',
    'throw new Error("Cannot require "+m);',
    '};',
  ].join('');
  const content = `${requireShim}\n${injectedCode}`;
  fs.writeFileSync(
    './packages/kit-bg/src/desktopApis/injectedDesktopCode.text-js',
    content,
  );
  console.log('Generated injectedDesktopCode.text-js');
})();

// Generate preload-webview.js: contextBridge preload + embedded provider injection
(function generatePreloadWebview() {
  // require("electron") shim: maps to window.__onekeyDesktopBridge exposed by contextBridge
  const requireShim = [
    'var require=function(m){',
    'if(m==="electron"){return{ipcRenderer:{',
    'on:function(ch,cb){window.__onekeyDesktopBridge.onHostMessage(function(d){cb({},d);});},',
    'sendToHost:function(ch,d){window.__onekeyDesktopBridge.sendToHost(ch,d);}',
    '}};}',
    'throw new Error("Cannot require "+m);',
    '};',
  ].join('');
  const fullProviderCode = `${requireShim}\n${injectedCode}`;

  const preloadContent = `/* eslint-disable */
/**
 * AUTO-GENERATED by copy-injected.js — do not edit manually.
 *
 * Webview preload script (contextIsolation: true, sandbox: true).
 * 1. Exposes a minimal IPC bridge via contextBridge.
 * 2. Injects the Web3 provider (injectedDesktop.js) into the page's main world
 *    via webFrame.executeJavaScript (DOM is not available at preload time).
 */
var electron = require('electron');
var contextBridge = electron.contextBridge;
var ipcRenderer = electron.ipcRenderer;
var webFrame = electron.webFrame;

var HOST_CHANNEL = 'JsBridgeDesktopHostToInjected';

// --- IPC bridge (accessible from page world as window.__onekeyDesktopBridge) ---
contextBridge.exposeInMainWorld('__onekeyDesktopBridge', {
  sendToHost: function (channel, data) {
    ipcRenderer.sendToHost(channel, data);
  },
  onHostMessage: function (callback) {
    ipcRenderer.on(HOST_CHANNEL, function (_event, data) {
      callback(data);
    });
  },
});

// --- Inject provider into page main world ---
// webFrame.executeJavaScript runs code in the main world's V8 context.
// Called from preload, it executes before the page's own scripts.
webFrame.executeJavaScript(${JSON.stringify(fullProviderCode)}).catch(function (err) {
  console.error('[OneKey] Failed to inject provider', err);
});
`;

  fs.writeFileSync('./apps/desktop/public/static/preload.js', preloadContent);
  console.log('Generated preload.js (webview preload with embedded provider)');
})();

// Copy to Extension injected.js
copyFile(
  './node_modules/@onekeyfe/cross-inpage-provider-injected/dist/injected/injectedExtension.js',
  './apps/ext/src/entry/injected.js',
);
copyFile(
  './apps/ext/src/entry/injected.js',
  './apps/ext/src/entry/injected.text-js',
);

// Copy to Native injectedCode
copyFile(
  './node_modules/@onekeyfe/cross-inpage-provider-injected/dist/injected/injectedNative.js',
  './packages/kit/src/components/WebView/injectedNative.text-js',
);

// Copy index html
copyFile(
  './packages/shared/src/web/index.html.ejs',
  './packages/shared/src/web/index.html',
);

// Copy hardware js-sdk iframe files to desktop
const jsSdkDestDir = './apps/desktop/public/static/js-sdk/';
ensureDirectoryExistence(jsSdkDestDir);

const srcDir = path.join(
  __dirname,
  '..',
  '..',
  'node_modules',
  '@onekeyfe',
  'hd-web-sdk',
  'build',
);
copyRecursiveSync(srcDir, jsSdkDestDir);
console.log(`Copied ${srcDir} to ${jsSdkDestDir}`);

// Build and copy web-embed
const webEmbedScript = path.join(__dirname, 'web-embed.js');
execSync(`node "${webEmbedScript}"`, { stdio: 'inherit' });

console.log('All files copied successfully.');
