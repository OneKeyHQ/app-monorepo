// Font consistency check
//
// iOS can unload custom fonts registered at runtime under memory pressure when the app is
// backgrounded, so fonts are registered natively, and native registration is the ONLY path:
// loading them again through expo-font would ship a second copy of every ttf (Metro turns
// `require(ttf)` into res/raw assets while fonts-sync already writes native asset copies).
//
// Registration points kept in sync here:
//   1. Info.plist UIAppFonts — native iOS font registration (resolved by PostScript name)
//   2. Podfile font_files   — copies font files into the Xcode project during pod install
//   3. Android assets/fonts — synchronous ReactFontManager lookup by JS family name
//   4. web-fonts.css        — @font-face for web/desktop/extension builds
//
// It also verifies that each font file's internal PostScript name matches the family name
// used by the UI (iOS UIAppFonts registers fonts by PostScript name), and fails if a
// JS-side expo-font loader is reintroduced.
//
// Brand sans entries use computed keys (BRAND_FONT_NATIVE_FAMILY.*) resolved from the
// manifest generated by `yarn fonts:sync`, and fixed slot file names (brand/BrandSans-*.ttf).

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { exit } = require('process');

const {
  getLicenseDescription,
  getPostScriptName,
} = require('../scripts/font-file-utils');

const getTimestamp = () => new Date().toLocaleTimeString();

function hasForbiddenRuntimeFontLoader(source) {
  const importsExpoFont =
    /(?:from\s+['"]expo-font['"]|require\(\s*['"]expo-font['"]|useFonts\()/.test(
      source,
    );
  const requiresTtf = /require\(\s*['"][^'"]+\.ttf['"]/.test(source);
  return importsExpoFont || requiresTtf;
}

function runFontCheck() {
  const startTime = Date.now();

  console.log(`[${getTimestamp()}] Font consistency check started...`);

  const rootDir = path.resolve(__dirname, '../..');

  // Source of truth: useLoadCustomFonts.ts (the fonts actually used at runtime)
  const useLoadCustomFontsPath = path.join(
    rootDir,
    'packages/components/src/hocs/Provider/hooks/useLoadCustomFonts.ts',
  );
  const fontsSrcDir = path.join(
    rootDir,
    'packages/components/src/hocs/Provider/fonts',
  );
  const infoPlistPath = path.join(
    rootDir,
    'apps/mobile/ios/OneKeyWallet/Info.plist',
  );
  const podfilePath = path.join(rootDir, 'apps/mobile/ios/Podfile');
  const androidFontsDir = path.join(
    rootDir,
    'apps/mobile/android/app/src/main/assets/fonts',
  );

  let hasError = false;

  function error(msg) {
    console.error(`  ✖ ${msg}`);
    hasError = true;
  }

  function ok(msg) {
    console.log(`  ✓ ${msg}`);
  }

  // 1. Declare the font slots that must exist in every registration point.
  // Brand sans faces are generated by `yarn fonts:sync` (family names come from the
  // manifest), mono faces are fixed. Keep this list in sync with
  // apps/mobile/scripts/__tests__/android-font-assets.test.js.
  const brandManifestPath = path.join(fontsSrcDir, 'brand/manifest.ts');
  if (!fs.existsSync(brandManifestPath)) {
    error(`${brandManifestPath} is missing. Run \`yarn fonts:sync\` first.`);
    exit(1);
  }
  const brandFamily = {};
  for (const [, slot, family] of fs
    .readFileSync(brandManifestPath, 'utf-8')
    .matchAll(/^\s+(\w+): '([^']+)',$/gm)) {
    brandFamily[slot] = family;
  }

  const fontSlots = [
    { brandSlot: 'regular', fileName: 'brand/BrandSans-Regular.ttf' },
    { brandSlot: 'medium', fileName: 'brand/BrandSans-Medium.ttf' },
    { brandSlot: 'semibold', fileName: 'brand/BrandSans-SemiBold.ttf' },
    { brandSlot: 'bold', fileName: 'brand/BrandSans-Bold.ttf' },
    { jsKey: 'GeistMono-Regular', fileName: 'GeistMono-Regular.ttf' },
    { jsKey: 'GeistMono-Medium', fileName: 'GeistMono-Medium.ttf' },
  ];
  const fontEntries = []; // { jsKey, fileName }
  for (const { brandSlot, jsKey: literalKey, fileName } of fontSlots) {
    const jsKey = literalKey ?? brandFamily[brandSlot];
    if (!jsKey) {
      error(
        `BRAND_FONT_NATIVE_FAMILY.${brandSlot} is not in the brand manifest`,
      );
    } else {
      fontEntries.push({ jsKey, fileName });
    }
  }
  fontEntries.sort((a, b) => a.fileName.localeCompare(b.fileName));

  if (fontEntries.length === 0) {
    error('No font slots declared in development/lint/font.js');
    exit(1);
  }

  // Guard: native registration is the only font loading path. If expo-font or a ttf
  // require comes back here, every font is shipped twice again (see PR #14418).
  const useLoadContent = fs.readFileSync(useLoadCustomFontsPath, 'utf-8');
  if (hasForbiddenRuntimeFontLoader(useLoadContent)) {
    error(
      'useLoadCustomFonts.ts must not load fonts (expo-font / require(ttf)); native registration already provides them',
    );
  }

  // Relative to the Provider fonts dir, as listed in the Podfile.
  const registeredFonts = fontEntries.map((e) => e.fileName);
  // The Xcode bundle and UIAppFonts are flat, so they use base names.
  const registeredFontBaseNames = registeredFonts.map((f) => path.basename(f));

  console.log(`\nChecking ${fontEntries.length} native font slots`);

  // 2. Check font files exist on disk + JS key matches PostScript name
  console.log('\nChecking font files and PostScript name consistency...');
  for (const { jsKey, fileName } of fontEntries) {
    const filePath = path.join(fontsSrcDir, fileName);
    if (!fs.existsSync(filePath)) {
      error(
        `${fileName} registered in useLoadCustomFonts.ts but file is MISSING`,
      );
    } else {
      ok(`${fileName} exists`);

      const psName = getPostScriptName(filePath);
      if (!psName) {
        error(`${fileName} could not read PostScript name from font file`);
      } else if (psName !== jsKey) {
        error(
          `${fileName} PostScript name "${psName}" does NOT match family name "${jsKey}" — UI fontFamily would not resolve on iOS/Android`,
        );
      } else {
        ok(`${fileName} PostScript name "${psName}" matches JS key`);
      }
    }
  }

  // 3. Check Android assets by JS family name against the referenced Provider file
  console.log('\nChecking Android native font assets...');
  for (const { jsKey, fileName } of fontEntries) {
    const androidFileName = `${jsKey}.ttf`;
    const androidFilePath = path.join(androidFontsDir, androidFileName);
    const sourceFilePath = path.join(fontsSrcDir, fileName);
    if (!fs.existsSync(androidFilePath)) {
      error(`${androidFileName} MISSING from Android assets/fonts`);
    } else if (fs.existsSync(sourceFilePath)) {
      if (
        fs.readFileSync(androidFilePath).equals(fs.readFileSync(sourceFilePath))
      ) {
        ok(`${androidFileName} matches Provider ${fileName}`);
      } else {
        error(
          `${androidFileName} in Android assets/fonts does NOT match Provider ${fileName}`,
        );
      }
    }
  }

  // 4. Check Info.plist UIAppFonts
  console.log('\nChecking Info.plist UIAppFonts...');
  const plistContent = fs.readFileSync(infoPlistPath, 'utf-8');
  const uiAppFontsMatch = plistContent.match(
    /<key>UIAppFonts<\/key>\s*<array>([\s\S]*?)<\/array>/,
  );

  if (!uiAppFontsMatch) {
    error('UIAppFonts key not found in Info.plist');
  } else {
    const stringPattern = /<string>([^<]+)<\/string>/g;
    const plistFonts = [];
    let m;
    while ((m = stringPattern.exec(uiAppFontsMatch[1])) !== null) {
      plistFonts.push(m[1]);
    }

    for (const fontFile of registeredFontBaseNames) {
      if (plistFonts.includes(fontFile)) {
        ok(`${fontFile} declared in UIAppFonts`);
      } else {
        error(`${fontFile} MISSING from Info.plist UIAppFonts`);
      }
    }

    for (const plistFont of plistFonts) {
      if (!registeredFontBaseNames.includes(plistFont)) {
        error(
          `${plistFont} in Info.plist UIAppFonts but not declared in development/lint/font.js`,
        );
      }
    }
  }

  // 5. Check Podfile font_files list
  console.log('\nChecking Podfile font_files...');
  const podfileContent = fs.readFileSync(podfilePath, 'utf-8');
  const podfileFontMatch = podfileContent.match(
    /font_files\s*=\s*%w\[([^\]]+)\]/,
  );

  if (!podfileFontMatch) {
    error('font_files list not found in Podfile');
  } else {
    const podfileFonts = podfileFontMatch[1].trim().split(/\s+/);

    for (const fontFile of registeredFonts) {
      if (podfileFonts.includes(fontFile)) {
        ok(`${fontFile} listed in Podfile`);
      } else {
        error(`${fontFile} MISSING from Podfile font_files`);
      }
    }

    for (const podFont of podfileFonts) {
      if (!registeredFonts.includes(podFont)) {
        error(
          `${podFont} in Podfile font_files but not declared in development/lint/font.js`,
        );
      }
    }
  }

  // 6. Every committed font must be openly licensed. The licensed brand font is
  // fetched by `yarn fonts:sync` and must never be committed to this public repo.
  console.log('\nChecking committed font licenses...');
  const OPEN_FONT_LICENSE_PATTERN = /SIL Open Font License|Apache License/i;
  // Staged by `fonts-sync.js --stage-eas` in CI only; not gitignored so EAS uploads it.
  const EAS_STAGING_DIR = '.eas-private-fonts/';
  const trackedFiles = execFileSync('git', ['ls-files', '-z'], {
    cwd: rootDir,
    encoding: 'utf-8',
    maxBuffer: 64 * 1024 * 1024,
  })
    .split('\0')
    .filter(Boolean);
  for (const file of trackedFiles) {
    if (file.startsWith(EAS_STAGING_DIR)) {
      error(
        `${file} is a CI-only staged private font and must not be committed`,
      );
    } else if (/\.(ttf|otf|woff2?)$/i.test(file)) {
      const filePath = path.join(rootDir, file);
      const license = /\.(ttf|otf)$/i.test(file)
        ? getLicenseDescription(filePath)
        : null;
      if (license && OPEN_FONT_LICENSE_PATTERN.test(license)) {
        ok(`${file} is openly licensed`);
      } else {
        error(
          `${file} is not marked as SIL OFL or Apache licensed. Commercial fonts must come from \`yarn fonts:sync\`, not git.`,
        );
      }
    }
  }

  // Summary
  const duration = ((Date.now() - startTime) / 1000).toFixed(2);
  console.log('');

  if (hasError) {
    console.error(
      `[${getTimestamp()}] Font consistency check FAILED. (${duration}s)`,
    );
    console.error('\nAll font slots must:');
    console.error(
      "  1. Have a JS key that matches the font file's PostScript name",
    );
    console.error('  2. Be declared in Info.plist UIAppFonts');
    console.error('  3. Be listed in Podfile font_files');
    console.error(
      '  4. Have an Android assets/fonts/<JS key>.ttf copy matching the Provider file',
    );
    console.error('  5. Be openly licensed if committed to git');
    exit(1);
  } else {
    console.log(
      `[${getTimestamp()}] Font consistency check passed. (${duration}s)`,
    );
  }
}

if (require.main === module) {
  runFontCheck();
}

module.exports = {
  hasForbiddenRuntimeFontLoader,
};
