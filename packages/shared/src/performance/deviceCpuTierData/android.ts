export function getAndroidDeviceCpuTier({
  manufacturer,
  model,
}: {
  manufacturer: string;
  model: string;
}): TKnownDeviceCpuTier | undefined {
  if (
    !Object.prototype.hasOwnProperty.call(
      ANDROID_DEVICE_CPU_TIER_BY_MANUFACTURER,
      manufacturer,
    )
  ) {
    return undefined;
  }
  const models = ANDROID_DEVICE_CPU_TIER_BY_MANUFACTURER[manufacturer];
  if (!Object.prototype.hasOwnProperty.call(models, model)) {
    return undefined;
  }
  return models[model];
}
